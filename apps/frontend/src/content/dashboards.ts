/** A message from the Olympiad API in the dashboard's language. */
export function apiMessage(message: string, lang: OlympiadLang) {
  if (lang === "en") return message;
  for (const [pattern, gujarati] of API_MESSAGES) {
    const match = message.match(pattern);
    if (match) return typeof gujarati === "string" ? gujarati : gujarati(match);
  }
  return message;
}
